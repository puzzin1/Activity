def get_config_filename():
    """
    Генерирует имя файла конфигурации на основе текущей даты.
    Файл создается один раз в день и используется при повторных запусках.
    
    Returns:
        str: Имя файла в формате 'activity_config_YYYYMMDD.json'
    """
    return f"activity_config_{datetime.now().strftime('%Y%m%d')}.json"


def time_str_to_minutes(time_str):
    """
    Конвертирует строку времени 'HH:MM' в минуты с начала дня.
    
    Args:
        time_str (str): Время в формате 'HH:MM'
    
    Returns:
        int: Количество минут с начала дня (0-1439)
    
    Example:
        time_str_to_minutes('09:30') -> 570
        time_str_to_minutes('14:15') -> 855
    """
    h, m = map(int, time_str.split(':'))
    return h * 60 + m


def minutes_to_time_str(minutes):
    """
    Конвертирует минуты с начала дня в строку 'HH:MM'.
    
    Args:
        minutes (int): Количество минут с начала дня
    
    Returns:
        str: Время в формате 'HH:MM'
    
    Example:
        minutes_to_time_str(570) -> '09:30'
        minutes_to_time_str(855) -> '14:15'
    """
    h = minutes // 60
    m = minutes % 60
    return f"{h:02d}:{m:02d}"


def generate_schedule(config):
    """
    Генерирует расписание работы и перерывов на день на основе конфигурации.
    
    Расписание включает:
    - Время начала и окончания рабочего дня
    - Обеденный перерыв
    - Короткие перерывы (туалет, кофе и т.д.)
    
    Для ПЯТНИЦЫ используется специальное расписание окончания работы.
    
    Все перерывы распределяются равномерно в течение дня для естественности.
    
    Args:
        config (dict): Словарь с настройками программы
    
    Returns:
        dict: Словарь с расписанием, содержащий:
            - work_start: время начала работы
            - work_end: время окончания работы
            - lunch_start: время начала обеда
            - lunch_end: время окончания обеда
            - breaks: список коротких перерывов
            - is_friday: флаг, является ли день пятницей
    """
    schedule = {}
    
    # Проверяем, сегодня ли пятница (weekday: 0=Пн, 1=Вт, 2=Ср, 3=Чт, 4=Пт)
    is_friday = datetime.now().weekday() == 4
    schedule['is_friday'] = is_friday
    
    # 1. Определяем рабочее время
    work_start = random.randint(
        time_str_to_minutes(config['work_start_min']),
        time_str_to_minutes(config['work_start_max'])
    )
    
    # Для пятницы используем специальное время окончания
    if is_friday:
        work_end = random.randint(
            time_str_to_minutes(config['friday_work_end_min']),
            time_str_to_minutes(config['friday_work_end_max'])
        )
    else:
        work_end = random.randint(
            time_str_to_minutes(config['work_end_min']),
            time_str_to_minutes(config['work_end_max'])
        )
    
    schedule['work_start'] = minutes_to_time_str(work_start)
    schedule['work_end'] = minutes_to_time_str(work_end)
    
    # 2. Определяем продолжительность обеда
    lunch_duration = random.randint(
        config['lunch_duration_min'],
        config['lunch_duration_max']
    )
    
    # 3. Определяем время обеда (случайно в заданном диапазоне)
    lunch_earliest = time_str_to_minutes(config['lunch_start_min'])
    lunch_latest = time_str_to_minutes(config['lunch_end_max']) - lunch_duration
    
    # Убеждаемся, что обед начинается после начала работы и заканчивается до конца
    lunch_earliest = max(lunch_earliest, work_start + 60)  # Минимум через час после начала
    lunch_latest = min(lunch_latest, work_end - lunch_duration - 30)  # За 30 мин до конца
    
    if lunch_earliest <= lunch_latest:
        lunch_start = random.randint(lunch_earliest, lunch_latest)
    else:
        # Если диапазон некорректен, используем середину рабочего дня
        lunch_start = (work_start + work_end) // 2 - lunch_duration // 2
    
    schedule['lunch_start'] = minutes_to_time_str(lunch_start)
    schedule['lunch_end'] = minutes_to_time_str(lunch_start + lunch_duration)
    
    # 4. Определяем остальные перерывы (туалет, кофе и т.д.)
    total_break_time = random.randint(config['total_break_min'], config['total_break_max'])
    remaining_break_time = total_break_time - lunch_duration
    
    # Генерируем короткие перерывы (3-8 минут каждый)
    breaks = []
    while remaining_break_time > 0:
        break_duration = min(random.randint(3, 8), remaining_break_time)
        breaks.append(break_duration)
        remaining_break_time -= break_duration
    
    # 5. Распределяем перерывы равномерно в течение дня
    # Разделяем рабочий день на два периода: до обеда и после обеда
    
    work_periods = []
    # Период до обеда
    work_periods.append((work_start, lunch_start))
    # Период после обеда
    work_periods.append((lunch_start + lunch_duration, work_end))
    
    schedule['breaks'] = []
    
    # Распределяем перерывы по периодам (поровну между утром и после обеда)
    breaks_per_period = [[], []]
    for i, break_dur in enumerate(breaks):
        period_idx = i % 2  # Чередуем между периодами
        breaks_per_period[period_idx].append(break_dur)
    
    # Размещаем перерывы в каждом периоде
    for period_idx, (period_start, period_end) in enumerate(work_periods):
        period_breaks = breaks_per_period[period_idx]
        if not period_breaks:
            continue
        
        period_duration = period_end - period_start
        available_time = period_duration - sum(period_breaks)
        
        if available_time > 0 and period_duration > 30:  # Если период достаточно длинный
            # Равномерно распределяем перерывы
            num_breaks = len(period_breaks)
            segment_size = period_duration // (num_breaks + 1)
            
            for i, break_dur in enumerate(period_breaks):
                # Размещаем перерыв в своем сегменте с небольшой случайностью
                break_start = period_start + segment_size * (i + 1) + random.randint(-10, 10)
                # Ограничиваем, чтобы перерыв не вылез за границы периода
                break_start = max(period_start + 15, min(break_start, period_end - break_dur - 15))
                
                schedule['breaks'].append({
                    'start': minutes_to_time_str(break_start),
                    'end': minutes_to_time_str(break_start + break_dur),
                    'duration': break_dur
                })
    
    # Сортируем перерывы по времени для красивого отображения
    schedule['breaks'].sort(key=lambda x: time_str_to_minutes(x['start']))
    
    return schedule


def load_or_create_config():
    """
    Загружает конфигурацию из существующего файла или создает новую.
    
    Если файл конфигурации для текущей даты существует, он загружается.
    В противном случае создается новая конфигурация с расписанием на день.
    
    Returns:
        tuple: (config, schedule) - кортеж из словаря настроек и расписания
    
    Raises:
        Exception: При ошибке загрузки выводится сообщение и создается новая конфигурация
    """
    config_file = get_config_filename()
    
    # Пытаемся загрузить существующий файл
    if os.path.exists(config_file):
        # Загрузка существующего файла - сообщение только в возвращаемые данные
        try:
            with open(config_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
                return data['config'], data['schedule']
        except Exception as e:
            # Ошибка будет видна в консоли
            print(f"⚠️  Ошибка загрузки конфигурации: {e}")
            print(f"   Создание новой конфигурации...")
    
    # Создаем новую конфигурацию - сообщение только для нового файла
    config = DEFAULT_CONFIG.copy()
    schedule = generate_schedule(config)
    
    # Сохраняем в файл
    try:
        with open(config_file, 'w', encoding='utf-8') as f:
            json.dump({
                'config': config,
                'schedule': schedule,
                'created_at': datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
                'note': 'Этот файл содержит настройки и расписание на день. ' +
                       'Редактируйте config для изменения параметров работы программы.'
            }, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"⚠️  Ошибка сохранения конфигурации: {e}")
    
    return config, schedule


